#!/usr/bin/env python3
"""
Build all cargo-translocation runs with the CLEAN protocol:
    1. minimize with the cargo HELD at its data-file position (z = 12.5)
    2. equilibrate chains (default 20000 steps) with the cargo still held
    3. release the cargo, reset timestep, start the DCD, run production
       (default 2,000,000 steps; halts early if cargo z < -12.5:
        r <= 10 -> PASSED (through the pore), r > 10 -> OUTSIDE (rejected))

Folder layout (same as pe_pm_pp_analysis_radial.py, so the analysis works unchanged):
    <out>/<pct>_run_<n>/            sigma 0.5
    <out>/<pct>_<code>_run_<n>/     other sigmas (code = 1, 2, ..., 8)
    each folder: <pct>_05.data, in.lammps

Usage:
    python setup_runs.py --data-dir /path/to/datafiles --out /path/to/new_runs
    (data files named <pct>_05.data, e.g. 0_05.data, 25_05.data ...)

Options:
    --pcts 0 25 50 75 100          rigidities
    --sigmas 0.5 1 2 3 4 5 6 7 8   cargo sizes
    --nruns 100                    runs per (rigidity, sigma)
    --start-run 1                  first run number (51 = add runs 51-100 to an existing set of 50)
    --prod-steps 2000000           production limit (runs longer = stuck/trapped)
    --equil-steps 20000
    --cargo-langevin 1.0           Langevin thermostat on the cargo (damping time 1 tau); off if omitted
    --membrane                     wall at |z| < 12.5 outside the pore (nuclear envelope):
                                   the cargo can only cross through the pore
    --escape 30                    stop the run when the cargo is > 30 from the pore mouth (0,0,12.5),
                                   above or beside the pore -> "ESCAPED -> rejected" in stdout.log (0 = off).
                                   Never fires inside the pore (farthest pore point is 26.9 away).
    --k-rule 10 7 5 10             angle K (theta0 = 180) set per angle type from the beads it joins:
                                   3 rigid -> 10, any 2 rigid -> 7, any 1 rigid -> 5,
                                   anchor + rigid -> 10, all others 0. Rigid = type 2, anchor = type 1
                                   (original type names from the data file comments).
    --angles-dir DIR               optional: angles_<pct>.in overrides the rule for that rigidity

Atom types are read from each data file:
    anchor = type 1, cargo = the type with exactly one atom,
    shell  = the other type whose atoms all sit on the pore wall (r = 10, |z| <= 12.5),
    polymer = all remaining types.
Cargo pair coefficients follow your convention: sigma_ij = (sigma + 1)/2,
cutoff = 2^(1/6) sigma_ij (WCA); cargo-cargo sigma = sigma.

It also writes:
    jobs.txt          one run folder per line
    run_array.slurm   SLURM array job (edit partition/time/LAMMPS module)
    run_all.sh        run all folders on your node: PAR runs at a time, NP MPI ranks each
                      (default LAMMPS: ~/lammps-29Aug2024/build_full/lmp)
"""
import argparse, os, random, shutil, sys
import numpy as np

WCA = 2 ** (1 / 6)

TEMPLATE = """# ---- generated by setup_runs.py : rigidity {pct}%, cargo sigma {sigma}, run {run} ----
units           lj
dimension       3
boundary        f f f
atom_style      full
read_data       {datafile}
comm_modify     cutoff {comm_cut:.2f}
log             logfile_run{run}.txt

group anchor  type {t_anchor}
group polymer type {t_polymer}
group shell   type {t_shell}
group cargo   type {t_cargo}
group fixed   union anchor shell

fix freeze fixed setforce 0.0 0.0 0.0
fix hold_cargo cargo setforce 0.0 0.0 0.0      # cargo held at its start position
velocity fixed set 0.0 0.0 0.0

pair_style      lj/cut {wca:.9f}
{pair_block}
pair_modify shift yes

bond_style harmonic
bond_coeff 1 100.0 1.0
special_bonds lj 0.0 1.0 1.0
angle_style harmonic
{angle_block}

neighbor 1.0 bin                                # larger skin: fewer list rebuilds (same physics)
neigh_modify delay 0 every 1 check yes
neigh_modify exclude group fixed fixed          # frozen anchors/shell do not interact with each other

compute cargox cargo reduce sum x
compute cargoy cargo reduce sum y
compute cargoz cargo reduce sum z
thermo_style custom step temp pe ke etotal press c_cargox c_cargoy c_cargoz
thermo_modify norm no                          # log shows the real cargo x, y, z

# ---- 1. minimization: only chains move, cargo stays put ----
min_modify dmax 0.1
minimize 1.0e-8 1.0e-8 10000 100000

# ---- 2. equilibration: chains relax around the held cargo ----
velocity polymer create 1.0 {seed} mom yes rot yes
velocity cargo set 0.0 0.0 0.0
fix nvt_polymer polymer nvt temp 1.0 1.0 0.5
fix nve_cargo cargo nve
timestep 0.005
thermo 1000
run {equil}

# ---- 3. production: release cargo, DCD frame 0 = release ----
unfix hold_cargo
{lang_line}reset_timestep 0
dump traj all dcd 100 dump_run{run}.dcd
variable cargoz equal c_cargoz
variable cargor equal sqrt(c_cargox^2+c_cargoy^2)
variable passed  equal "v_cargoz < -12.5 && v_cargor <= 10.0"    # left through the pore bottom
variable outside equal "v_cargoz < -12.5 && v_cargor > 10.0"     # went around the pore = rejected
fix stopwatch all halt 1 v_passed == 1 error continue
fix outside_stop all halt 1 v_outside == 1 error continue
{extra_block}run {prod}
if "${{passed}} == 1" then &
    "print 'Simulation {run}: cargo PASSED'" &
elif "${{outside}} == 1" &
    "print 'Simulation {run}: cargo crossed OUTSIDE the pore -> rejected'" &
{escape_print}else &
    "print 'Simulation {run}: cargo did NOT pass within {prod} steps -> stuck'"
write_restart restart_run{run}.restart
print "Simulation {run} completed"
"""


def read_types(fn):
    L = open(fn).read().splitlines()
    ntypes = int(next(l.split()[0] for l in L if "atom types" in l))
    nangtypes = next((int(l.split()[0]) for l in L if "angle types" in l), 0)
    i = next(k for k, l in enumerate(L) if l.strip().startswith("Atoms")) + 1
    while not L[i].strip():
        i += 1
    t, xyz = [], []
    for l in L[i:]:
        if not l.strip():
            break
        p = l.split("#")[0].split()
        t.append(int(p[2])); xyz.append([float(p[4]), float(p[5]), float(p[6])])
    t = np.array(t); xyz = np.array(xyz); r = np.hypot(xyz[:, 0], xyz[:, 1])
    cargo = [k for k in range(1, ntypes + 1) if (t == k).sum() == 1]
    if len(cargo) != 1:
        sys.exit(f"{fn}: cannot identify the cargo type (need exactly one type with one atom)")
    cargo = cargo[0]
    shell = [k for k in range(2, ntypes + 1) if k != cargo and (t == k).sum() > 50
             and np.all(np.abs(r[t == k] - 10.0) < 0.3) and np.all(np.abs(xyz[t == k, 2]) <= 12.6)]
    if len(shell) != 1:
        sys.exit(f"{fn}: cannot identify the shell type (found {shell})")
    shell = shell[0]
    polymer = [k for k in range(2, ntypes + 1) if k not in (cargo, shell)]
    cz = xyz[t == cargo][0]
    return dict(n=ntypes, nang=nangtypes, anchor=1, cargo=cargo, shell=shell, polymer=polymer, cargo_xyz=cz)


def auto_angle_block(fn, k3, k2, k1, kanchor,
                     rigid_name=2, anchor_name=1):

    """
    Explicit angle stiffness assignment.

    Exact rules:

        1-2-2  -> K = 5
        2-2-2  -> K = 5
        2-2-3  -> K = 3
        2-3-3  -> K = 2
        3-3-3  -> K = 0

    The order of atoms in an angle does not matter:
        2-2-3 = 2-3-2 = 3-2-2
    """

    L = open(fn).read().splitlines()

    # ---------------------------------------------------------
    # Read atom types from Atoms section
    # ---------------------------------------------------------
    i = next(
        k for k, l in enumerate(L)
        if l.strip().startswith("Atoms")
    ) + 1

    while not L[i].strip():
        i += 1

    name = {}

    for l in L[i:]:
        if not l.strip():
            break

        body, _, com = l.partition("#")
        p = body.split()

        atom_id = int(p[0])
        atom_type = int(p[2])

        # If the comment contains the original atom type,
        # use it.
        if com.split():
            try:
                atom_type = int(com.split()[0])
            except ValueError:
                pass

        name[atom_id] = atom_type

    # ---------------------------------------------------------
    # Find Angles section
    # ---------------------------------------------------------
    j = next(
        (k for k, l in enumerate(L)
         if l.strip().startswith("Angles")),
        None
    )

    if j is None:
        return "angle_coeff * 0.0 180.0", []

    j += 1

    while not L[j].strip():
        j += 1

    # ---------------------------------------------------------
    # Collect atom-type combinations for each angle type
    # ---------------------------------------------------------
    comp = {}

    for l in L[j:]:

        if not l.strip():
            break

        p = l.split("#")[0].split()

        angle_type = int(p[1])

        a1 = int(p[2])
        a2 = int(p[3])
        a3 = int(p[4])

        combination = (
            name[a1],
            name[a2],
            name[a3]
        )

        comp.setdefault(angle_type, set()).add(combination)

    # ---------------------------------------------------------
    # Explicit K assignment
    # ---------------------------------------------------------
    lines = []
    table = []

    for angle_type in sorted(comp):

        combinations = comp[angle_type]
        ks = set()

        for c in combinations:

            # Order-independent combination
            sc = tuple(sorted(c))

            # =================================================
            # YOUR EXPLICIT RULES
            # =================================================

            if sc == (1, 2, 2):
                k = 5.0

            elif sc == (2, 2, 2):
                k = 5.0

            elif sc == (2, 2, 3):
                k = 3.0

            elif sc == (2, 3, 3):
                k = 2.0

            elif sc == (3, 3, 3):
                k = 0.0

            # Anything else gets zero
            else:
                k = 0.0

            ks.add(k)

        # -----------------------------------------------------
        # Safety check:
        # one angle type must not contain combinations
        # requiring different K values
        # -----------------------------------------------------
        if len(ks) > 1:
            sys.exit(
                f"{fn}: angle type {angle_type} contains "
                f"combinations {combinations} requiring "
                f"different K values {ks}"
            )

        k = ks.pop()

        lines.append(
            f"angle_coeff {angle_type} {k:g} 180.0    # "
            + ", ".join(
                "-".join(map(str, c))
                for c in sorted(combinations)
            )
        )

        table.append(
            (angle_type, sorted(combinations), k)
        )

    return "\n".join(lines), table


def pair_block(T, sigma):
    lines, n = [], T["n"]
    sij = (sigma + 1.0) / 2.0
    for i in range(1, n + 1):
        for j in range(i, n + 1):
            if i == T["cargo"] and j == T["cargo"]:
                # one cargo only: no self pair. A large cutoff here would set the neighbor
                # stencil for every atom and slow the run up to 4x for large sigma.
                lines.append(f"pair_coeff {i} {j} 0.0 1.0 1.0")
            elif T["cargo"] in (i, j):
                lines.append(f"pair_coeff {i} {j} 1.0 {sij:.4f} {WCA * sij:.9f}")
            else:
                lines.append(f"pair_coeff {i} {j} 1.0 1.0 {WCA:.9f}")
    return "\n".join(lines)


def extra_block(sigma, membrane, escape):
    out = ""
    if membrane:
        sw = (sigma + 1.0) / 2.0
        out += f"""# ---- membrane (nuclear envelope): the cargo cannot cross |z| < 12.5 outside the pore ----
region top     block INF INF INF INF  12.5 INF units box
region bottom  block INF INF INF INF  INF -12.5 units box
region porecyl cylinder z 0 0 10.5 -13.0 13.0 units box
region allowed union 3 top bottom porecyl
fix membrane cargo wall/region allowed lj126 1.0 {sw:.4f} {WCA * sw:.9f}
"""
    if 0 < escape <= 27.0:
        sys.exit("--escape must be > 27 (the far pore edge is 26.9 from the mouth)")
    if escape > 0:
        out += f"""# ---- escape: cargo more than {escape:g} from the pore mouth (0,0,12.5) = rejected; never true inside the pore (max 26.9) ----
variable dmouth  equal sqrt(c_cargox^2+c_cargoy^2+(c_cargoz-12.5)^2)
variable escaped equal "v_dmouth > {escape:g}"
fix escape all halt 100 v_escaped == 1 error continue
"""
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data-dir", default=".")
    ap.add_argument("--out", default="runs_clean")
    ap.add_argument("--pcts", nargs="+", default=["0", "25", "50", "75", "100"])
    ap.add_argument("--sigmas", nargs="+", default=["0.5", "1", "2", "3", "4", "5", "6", "7", "8"])
    ap.add_argument("--nruns", type=int, default=100, help="number of runs per (rigidity, sigma)")
    ap.add_argument("--start-run", type=int, default=1,
                    help="number of the first run, e.g. 51 to add runs 51-100 next to existing runs 1-50")
    ap.add_argument("--prod-steps", type=int, default=2000000)
    ap.add_argument("--equil-steps", type=int, default=20000)
    ap.add_argument("--angles-dir", default=None)
    ap.add_argument("--k-rule", type=float, nargs=4, default=[5.0, 5.0, 2.0, 5.0],
                    metavar=("K3", "K2", "K1", "KANCHOR"),
                    help="angle K for 3 / 2 / 1 rigid beads and for anchor+rigid (default 10 7 5 10); others 0")
    ap.add_argument("--cargo-langevin", type=float, default=None, metavar="DAMP",
                    help="add a Langevin thermostat on the cargo with this damping time (e.g. 1.0). Default: off")
    ap.add_argument("--membrane", action="store_true",
                    help="wall for the cargo at |z|<12.5 outside the pore (nuclear envelope): no crossing outside the pore")
    ap.add_argument("--escape", type=float, default=0.0, metavar="R",
                    help="halt when the cargo is more than R from the pore mouth (0,0,12.5) above the pore = rejected (0 = off)")
    ap.add_argument("--seed", type=int, default=12345, help="master seed for the per-run velocity seeds")
    a = ap.parse_args()
    rng = random.Random(a.seed)
    os.makedirs(a.out, exist_ok=True)
    jobs = []
    for pct in a.pcts:
        dfile = os.path.join(a.data_dir, f"{pct}k5_05.data")
        if not os.path.exists(dfile):
            sys.exit(f"missing data file {dfile}")
        T = read_types(dfile)
        afile = os.path.join(a.angles_dir, f"angles_{pct}.in") if a.angles_dir else None
        if afile and os.path.exists(afile):
            angle_block = open(afile).read().strip()
            print(f"  angles from {afile}")
        else:
            angle_block, table = auto_angle_block(dfile, *a.k_rule)
            print(f"  angle K from rule (3 rigid={a.k_rule[0]:g}, 2 rigid={a.k_rule[1]:g}, 1 rigid={a.k_rule[2]:g}, "
                  f"anchor+rigid={a.k_rule[3]:g}, else 0):")
            for at, cs, k in table:
                print(f"    type {at:3d}  {', '.join('-'.join(map(str, c)) for c in cs):28s} K = {k:g}")
        cz = T["cargo_xyz"]
        print(f"{pct}%: types anchor={T['anchor']} polymer={T['polymer']} shell={T['shell']} cargo={T['cargo']}; "
              f"cargo in data file at z={cz[2]:.2f}, r={np.hypot(cz[0], cz[1]):.2f}")
        for s in a.sigmas:
            sigma = float(s)
            code = "0.5" if sigma == 0.5 else f"{sigma:g}"
            for run in range(a.start_run, a.start_run + a.nruns):
                name = f"{pct}_run_{run}" if code == "0.5" else f"{pct}_{code}_run_{run}"
                d = os.path.join(a.out, name); os.makedirs(d, exist_ok=True)
                shutil.copy(dfile, os.path.join(d, f"{pct}_05.data"))
                txt = TEMPLATE.format(pct=pct, sigma=s, run=run, datafile=f"{pct}_05.data",
                                      comm_cut=max(3.0, WCA * (sigma + 1) / 2 + 0.5),
                                      t_anchor=T["anchor"], t_polymer=" ".join(map(str, T["polymer"])),
                                      t_shell=T["shell"], t_cargo=T["cargo"], wca=WCA,
                                      pair_block=pair_block(T, sigma), angle_block=angle_block,
                                      seed=rng.randint(10000, 9999999), equil=a.equil_steps, prod=a.prod_steps,
                                      lang_line=(f"fix lang_cargo cargo langevin 1.0 1.0 {a.cargo_langevin} {rng.randint(10000, 9999999)}\n"
                                                 if a.cargo_langevin else ""),
                                      extra_block=extra_block(sigma, a.membrane, a.escape),
                                      escape_print=(f'elif "${{escaped}} == 1" &\n    "print \'Simulation {run}: cargo ESCAPED -> rejected\'" &\n'
                                                    if a.escape > 0 else ""))
                open(os.path.join(d, "in.lammps"), "w").write(txt)
                jobs.append(os.path.abspath(d))
    open(os.path.join(a.out, "jobs.txt"), "w").write("\n".join(jobs) + "\n")
    n = len(jobs)
    open(os.path.join(a.out, "run_array.slurm"), "w").write(f"""#!/bin/bash
#SBATCH --job-name=cargo_clean
#SBATCH --array=1-{n}%100          # {n} runs, at most 100 at a time
#SBATCH --ntasks=1
#SBATCH --time=24:00:00            # EDIT
#SBATCH --partition=EDIT_ME        # EDIT
#SBATCH --output=slurm_%A_%a.out
module load lammps                 # EDIT: your LAMMPS module
LMP=lmp                            # EDIT: your LAMMPS executable (lmp, lmp_mpi, ...)
DIR=$(sed -n "${{SLURM_ARRAY_TASK_ID}}p" {os.path.abspath(os.path.join(a.out, 'jobs.txt'))})
cd "$DIR" && $LMP -in in.lammps -log none > stdout.log 2>&1
""")
    jobs_abs = os.path.abspath(os.path.join(a.out, 'jobs.txt'))
    open(os.path.join(a.out, "run_all.sh"), "w").write(f"""#!/bin/bash
# Runs every folder listed in jobs.txt.
#   PAR   = how many runs at the same time
#   NP    = MPI processes per run   (PAR x NP should not exceed the cores you have)
# Examples (20 cores):
#   bash run_all.sh            -> 5 runs at a time, 4 cores each   (default, best throughput)
#   PAR=1 NP=20 bash run_all.sh -> one run at a time on 20 cores     (like run_50_transport.sh)
# Finished runs (stdout.log contains 'completed') are skipped, so you can restart safely.
LMP_BIN=${{LMP_BIN:-~/lammps-29Aug2024/build_full/lmp}}
PAR=${{PAR:-5}}
NP=${{NP:-4}}
JOBS={jobs_abs}
export LMP_BIN NP
run_one() {{
    d="$1"
    if grep -q "completed" "$d/stdout.log" 2>/dev/null; then echo "skip  $d"; return; fi
    if ( cd "$d" && mpirun -np $NP "$LMP_BIN" -in in.lammps > stdout.log 2>&1 ); then
        echo "done  $d"
    else
        echo "FAIL  $d (see $d/stdout.log)" | tee -a failed_runs.txt
    fi
}}
export -f run_one
echo "running $(wc -l < $JOBS) runs: $PAR at a time, $NP MPI processes each"
xargs -a $JOBS -P $PAR -I{{}} bash -c 'run_one "$@"' _ {{}}
echo "all runs finished"; [ -f failed_runs.txt ] && echo "failed runs listed in failed_runs.txt"
""")
    os.chmod(os.path.join(a.out, "run_all.sh"), 0o755)
    print(f"\n{n} run folders written under {os.path.abspath(a.out)}")
    print("next:  cd", os.path.abspath(a.out), "&&  nohup bash run_all.sh > run_all.log 2>&1 &")
    print("   or: edit run_array.slurm and  sbatch run_array.slurm   (if you use SLURM)")


if __name__ == "__main__":
    main()
