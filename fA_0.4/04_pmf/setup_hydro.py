# ------------------------------------------------------------------ data file
def sections(L):
    """line index of each section header"""
    idx = {}
    for k, l in enumerate(L):
        s = l.split("#")[0].strip()
        if s in ("Masses", "Atoms", "Bonds", "Angles", "Velocities", "Dihedrals", "Impropers"):
            idx[s] = k
    return idx


def block(L, k):
    """lines of the section whose header is at line k"""
    i = k + 1
    while not L[i].strip():
        i += 1
    j = i
    while j < len(L) and L[j].strip():
        j += 1
    return i, j


def original_names(L, idx):
    """type -> original name, from Masses comments (e.g. ' 3 1.000000 # 4')"""
    names = {}
    i, j = block(L, idx["Masses"])
    for l in L[i:j]:
        body, _, com = l.partition("#")
        t = int(body.split()[0])
        try:
            names[t] = int(com.split()[0])
        except (ValueError, IndexError):
            names[t] = t
    return names


def prepare_data(src, dst, k_rule_fn, by_type):
    L = open(src).read().split("\n")
    idx = sections(L)
    ntypes = int(next(l.split()[0] for l in L if l.strip().endswith("atom types")))
    tname = original_names(L, idx)
    ai, aj = block(L, idx["Atoms"])
    atoms = []
    for l in L[ai:aj]:
        p = l.split("#")[0].split()
        atoms.append((int(p[0]), int(p[1]), int(p[2]), float(p[4]), float(p[5]), float(p[6])))
    ids = [a[0] for a in atoms]
    count = defaultdict(int)
    for a in atoms:
        count[a[2]] += 1
    msgs = []

    # ---- cargo: the one type with a single atom; add one if missing
    cargo = [k for k in range(1, ntypes + 1) if count[k] == 1]
    if len(cargo) > 1:
        sys.exit(f"{src}: more than one single-atom type {cargo}")
    if not cargo:
        ntypes += 1; cargo = ntypes; tname[cargo] = 6
        new_id = max(ids) + 1
        L = [re.sub(r"^\s*\d+(\s+atoms)", f" {len(atoms) + 1}\\1", l) if l.strip().endswith(" atoms") else l for l in L]
        L = [re.sub(r"^\s*\d+(\s+atom types)", f" {ntypes}\\1", l) if l.strip().endswith("atom types") else l for l in L]
        idx = sections(L); mi, mj = block(L, idx["Masses"])
        L.insert(mj, f" {cargo} 1.000000 # 6")
        idx = sections(L); ai, aj = block(L, idx["Atoms"])
        L.insert(aj, f"{new_id} {max(a[1] for a in atoms) + 1} {cargo} 0.000000 0.000000 0.000000 12.500000 # 6 C")
        msgs.append(f"no cargo in file -> added atom {new_id} (type {cargo}) at (0, 0, 12.5)")
    else:
        cargo = cargo[0]
        cz = next(a[3:] for a in atoms if a[2] == cargo)
        if abs(cz[2] - 12.5) > 0.01 or math.hypot(cz[0], cz[1]) > 0.01:
            msgs.append(f"WARNING cargo in file at ({cz[0]:.2f}, {cz[1]:.2f}, {cz[2]:.2f}), not (0, 0, 12.5)")

    by_name = defaultdict(list)
    for k, v in tname.items():
        by_name[v].append(k)
    anchor = by_name[1][0]
    shell = [k for k in range(1, ntypes + 1) if k not in (cargo, anchor) and count[k] > 50
             and all(abs(math.hypot(a[3], a[4]) - 10.0) < 0.3 and abs(a[5]) <= 12.6 for a in atoms if a[2] == k)]
    if len(shell) != 1:
        sys.exit(f"{src}: cannot identify the shell type (found {shell})")
    shell = shell[0]
    A = [k for k in by_name.get(5, []) if k != cargo]
    polymer = [k for k in range(1, ntypes + 1) if k not in (anchor, shell, cargo)]

    # ---- chains from bonds: position of every bead along its chain
    name = {int(a[0]): tname[a[2]] for a in atoms}
    idx = sections(L); bi, bj = block(L, idx["Bonds"])
    adj = defaultdict(list)
    for l in L[bi:bj]:
        p = l.split(); a_, b_ = int(p[2]), int(p[3]); adj[a_].append(b_); adj[b_].append(a_)
    pos = {}
    for a0 in [i for i, v in name.items() if v == 1]:
        seq, prev, cur = [a0], None, a0
        while True:
            nx = [n for n in adj[cur] if n != prev]
            if not nx:
                break
            prev, cur = cur, nx[0]; seq.append(cur)
        for k, i in enumerate(seq):
            pos[i] = k
    rpos = [pos[i] for i, v in name.items() if v == 2 and i in pos]
    B = max(rpos) if rpos else 0            # rigid region = chain positions 1..B
    eff = {}
    for i, v in name.items():
        if v == 5 and i in pos:
            eff[i] = 2 if pos[i] <= B else 3    # A counts as rigid / flexible by region
        else:
            eff[i] = v
    use = name if by_type else eff

    # ---- angles: one angle type per (sorted) effective combination
    ni, nj = block(L, idx["Angles"])
    combos, rows = {}, []
    for l in L[ni:nj]:
        p = l.split("#")[0].split()
        a3 = [int(x) for x in p[2:5]]
        key = tuple(sorted(use[x] for x in a3))
        combos.setdefault(key, len(combos) + 1)
        rows.append(f"{p[0]} {combos[key]} {a3[0]} {a3[1]} {a3[2]}")
    L[ni:nj] = rows
    L = [re.sub(r"^\s*\d+(\s+angle types)", f" {len(combos)}\\1", l) if l.strip().endswith("angle types") else l for l in L]
    # drop the old '# Angle Coeffs' comment block (it no longer matches)
    out, skip = [], False
    for l in L:
        if l.strip().startswith("# Angle Coeffs"):
            skip = True; continue
        if skip and l.strip().startswith("#"):
            continue
        skip = False
        out.append(l)
    open(dst, "w").write("\n".join(out))
    angle_lines, table = [], []
    for key, at in sorted(combos.items(), key=lambda x: x[1]):
        k = k_rule_fn(key)
        angle_lines.append(f"angle_coeff {at} {k:g} 180.0    # {'-'.join(map(str, key))}")
        table.append((at, key, k))
    return dict(n=ntypes, anchor=anchor, shell=shell, cargo=cargo, A=A, polymer=polymer,
                B=B, angle_block="\n".join(angle_lines), table=table, msgs=msgs)


# YOUR explicit angle rule, by original names (1 anchor, 2 rigid, 3 flexible, 5 A),
# order independent (1-5-2 = 1-2-5 = 2-5-1 ...). Everything not listed -> 0.
K_TABLE = {
    (1, 2, 2): 5.0,   # anchor + 2 rigid
    (2, 2, 2): 5.0,   # 3 rigid
    (2, 2, 3): 3.0,   # 2 rigid + 1 flexible
    (2, 3, 3): 2.0,   # 1 rigid + 2 flexible
    (1, 2, 5): 3.0,   # A between anchor and rigid
    (2, 2, 5): 3.0,   # 2 rigid + 1 A
    (2, 5, 5): 2.0,   # 1 rigid + 2 A
    (2, 3, 5): 2.0,   # 1 rigid + 1 A + 1 flexible
}


def k_rule(sc):
    return K_TABLE.get(tuple(sorted(sc)), 0.0)


def pair_block(T, sigma, aa_eps, aa_cut):
    lines = []
    sij = (sigma + 1.0) / 2.0
    for i in range(1, T["n"] + 1):
        for j in range(i, T["n"] + 1):
            if i == T["cargo"] and j == T["cargo"]:
                lines.append(f"pair_coeff {i} {j} 0.0 1.0 1.0              # single cargo: no self pair")
            elif T["cargo"] in (i, j):
                lines.append(f"pair_coeff {i} {j} 1.0 {sij:.4f} {WCA * sij:.9f}   # cargo WCA")
            elif i in T["A"] and j in T["A"]:
                lines.append(f"pair_coeff {i} {j} {aa_eps:g} 1.0 {aa_cut:g}              # A-A attraction")
            else:
                lines.append(f"pair_coeff {i} {j} 1.0 1.0 {WCA:.9f}")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("datafiles", nargs="+")
    ap.add_argument("--out", default=".")
    ap.add_argument("--sigmas", nargs="+", default=["0.5", "1", "2", "3", "4", "5", "6", "7", "8"])
    ap.add_argument("--nruns", type=int, default=50)
    ap.add_argument("--prod-steps", type=int, default=2000000)
    ap.add_argument("--equil-steps", type=int, default=20000)
    ap.add_argument("--cargo-langevin", type=float, default=1.0)
    ap.add_argument("--escape", type=float, default=60.0)
    ap.add_argument("--aa-eps", type=float, default=1.5)
    ap.add_argument("--aa-cut", type=float, default=2.5)
    ap.add_argument("--angle-by-region", action="store_true")
    ap.add_argument("--seed", type=int, default=12345)
    ap.add_argument("--no-start", action="store_true")
    ap.add_argument("--par", type=int, default=5)
    ap.add_argument("--np", type=int, default=4)
    ap.add_argument("--ntasks", type=int, default=20)
    ap.add_argument("--partition", default="small")
    ap.add_argument("--time", default="3-00:00:00")
    ap.add_argument("--lmp", default=LMP_BIN)
    a = ap.parse_args()
    if a.escape <= 27:
        sys.exit("--escape must be > 27 (the far pore edge is 26.9 from the mouth)")
    if a.par * a.np > a.ntasks:
        sys.exit(f"--par x --np = {a.par * a.np} is more than --ntasks {a.ntasks}")
    rng = random.Random(a.seed)
    base = os.path.abspath(a.out); os.makedirs(base, exist_ok=True)
    slurms = []
    for src in a.datafiles:
        fname = os.path.basename(src)
        sysname = re.sub(r"_?(05)?\.data$", "", fname)
        sysdir = os.path.join(base, sysname); os.makedirs(sysdir, exist_ok=True)
        run_data = os.path.join(sysdir, fname)
        if os.path.abspath(src) != run_data:
            shutil.copy(src, os.path.join(sysdir, fname + ".orig"))
        T = prepare_data(src, run_data, k_rule, not a.angle_by_region)
        print(f"\n=== {sysname}  ({fname})")
        for m in T["msgs"]:
            print("   " + m)
        print(f"   types: anchor={T['anchor']} polymer={T['polymer']} shell={T['shell']} A={T['A'] or 'none'} "
              f"cargo={T['cargo']};  rigid region = chain positions 1..{T['B']}")
        print(f"   pairs: all WCA" + (f", A-A eps {a.aa_eps:g} cutoff {a.aa_cut:g}" if T["A"] else " (no A type found)"))
        print("   angles (" + ("A counted as rigid/flexible by region" if a.angle_by_region else "by type names, A = 5") + "):")
        for at, key, k in T["table"]:
            print(f"      type {at:2d}  {'-'.join(map(str, key)):6s} K = {k:g}")
        jobs = []
        for s in a.sigmas:
            sigma = float(s)
            for run in range(1, a.nruns + 1):
                d = os.path.join(sysdir, f"sigma_{sigma:.1f}", f"run_{run}")
                os.makedirs(d, exist_ok=True)
                lang_seed = rng.randint(10000, 9999999)
                txt = TEMPLATE.format(
                    sys=sysname, sigma=s, run=run, datafile=os.path.relpath(run_data, d),
                    comm_cut=max(4.0, WCA * (sigma + 1) / 2 + 1.5),
                    pair_cut=max(WCA, a.aa_cut if T["A"] else WCA),
                    t_anchor=T["anchor"], t_polymer=" ".join(map(str, T["polymer"])), t_shell=T["shell"],
                    t_cargo=T["cargo"], pair_block=pair_block(T, sigma, a.aa_eps, a.aa_cut),
                    angle_block=T["angle_block"], seed=rng.randint(10000, 9999999),
                    equil=a.equil_steps, prod=a.prod_steps, escape=a.escape,
                    lang_line=(f"fix lang_cargo cargo langevin 1.0 1.0 {a.cargo_langevin:g} {lang_seed}\n"
                               if a.cargo_langevin > 0 else ""))
                open(os.path.join(d, "in.lammps"), "w").write(txt)
                jobs.append(os.path.relpath(d, sysdir))
        random.Random(a.seed + 1).shuffle(jobs)          # mixed order: every sigma fills in evenly
        open(os.path.join(sysdir, "jobs.txt"), "w").write("\n".join(jobs) + "\n")
        sl = os.path.join(sysdir, f"job_{sysname}.slurm")
        open(sl, "w").write(SLURM.format(sys=sysname, partition=a.partition, ntasks=a.ntasks, time=a.time,
                                         sysdir=sysdir, njobs=len(jobs), par=a.par, np=a.np,
                                         env=ENV_BLOCK, lmp=a.lmp))
        os.chmod(sl, 0o755)
        slurms.append(sl)
        print(f"   {len(jobs)} runs -> {sysdir}/sigma_*/run_*   job file {sl}")

    if a.no_start:
        print("\n--no-start: nothing started. Submit with:  " + "  ;  ".join(f"sbatch {s}" for s in slurms))
        return
    if shutil.which("sbatch"):
        for s in slurms:
            r = subprocess.run(["sbatch", s], stdout=subprocess.PIPE, stderr=subprocess.PIPE, universal_newlines=True)
            print(f"sbatch {os.path.basename(s)}: {(r.stdout or r.stderr).strip()}")
        print("check with:  squeue -u $USER")
    else:
        for s in slurms:
            log = s.replace(".slurm", ".log")
            subprocess.Popen(["nohup", "bash", s], stdout=open(log, "w"), stderr=subprocess.STDOUT,
                             start_new_session=True)
            print(f"no sbatch here -> started locally in background: bash {s}  (log {log})")


if __name__ == "__main__":
    main()
