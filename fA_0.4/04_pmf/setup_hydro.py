#!/usr/bin/env python3
"""
Hydrophobe (A-bead) cargo-translocation runs, clean protocol, ONE command:

    python setup_hydro.py 25_ck505.data 50_ck505.data 75_ck505.data

For every data file given it:
  1. reads the file (types from the Masses / atom comments = original names:
     1 anchor, 2 rigid, 3 flexible, 4 shell, 5 A, 6 cargo),
  2. adds the cargo at (0, 0, 12.5) if the file has none,
  3. sets angles with YOUR rule, by names, order independent (theta0 = 180):
        1-2-2 -> 5   2-2-2 -> 5   2-2-3 -> 3   2-3-3 -> 2
        1-2-5 -> 3 (A between anchor and rigid)   2-2-5 -> 3   2-5-5 -> 2   2-3-5 -> 2
        everything else -> 0   (edit K_TABLE to change)
     one angle type per atom-name combination is written into the run copy of the data file,
  4. pairs: everything WCA, except A-A: epsilon 2.0, sigma 1.0, cutoff 2.5,
     cargo-bead sigma = (sigma_c + 1)/2 with WCA cutoff,
  5. writes  <SYS>/sigma_<s>/run_<n>/in.lammps   (SYS = data file name without "05.data"),
  6. writes  <SYS>/job_<SYS>.slurm  (one job per rigidity) and submits it with sbatch
     (or, with no sbatch on the machine, starts the runs locally in the background).

Protocol (same as setup_runs.py): minimize with cargo held -> 20000 steps NVT (chains) with
cargo held -> release, Langevin on the cargo, DCD every 100 steps, stop at:
   z < -12.5 and r <= 10  -> PASSED       z < -12.5 and r > 10 -> OUTSIDE (rejected)
   > ESCAPE from (0,0,12.5) -> ESCAPED    2,000,000 steps      -> stuck

Options (defaults = what you run now):
   --sigmas 0.5 1 2 3 4 5 6 7 8   --nruns 50   --prod-steps 2000000   --equil-steps 20000
   --cargo-langevin 1.0   --escape 60   --aa-eps 1.5   --aa-cut 2.5
   --angle-by-region      instead count an A bead as rigid (2) in the rigid region and flexible (3)
                          in the flexible region before applying the rule
   --no-start             only write the folders, do not submit / start
   --par 5 --np 4         runs at the same time x MPI ranks per run (par x np = cores of the job)
   --partition small --time 3-00:00:00 --ntasks 20
Re-running the same command is safe: finished runs are skipped when the job starts.
"""
